CREATE TABLE helpdesk.users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    full_name  VARCHAR(150) NOT NULL,
    role       VARCHAR(30)  NOT NULL,
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE helpdesk.categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE helpdesk.tickets
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description TEXT         NOT NULL,
    status      VARCHAR(40)  NOT NULL,
    priority    VARCHAR(30)  NOT NULL,
    creator_id  BIGINT       NOT NULL,
    CONSTRAINT fk_tickets_creator
        FOREIGN KEY (creator_id) REFERENCES helpdesk.users (id),
    assignee_id BIGINT,
    CONSTRAINT fk_tickets_assignee
        FOREIGN KEY (assignee_id) REFERENCES helpdesk.users (id),
    category_id BIGINT       NOT NULL,
    CONSTRAINT fk_tickets_category
        FOREIGN KEY (category_id) REFERENCES helpdesk.categories (id),
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL
);

CREATE TABLE helpdesk.comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT    NOT NULL,
    CONSTRAINT fk_comments_ticket
        FOREIGN KEY (ticket_id) REFERENCES helpdesk.tickets (id),
    author_id  BIGINT    NOT NULL,
    CONSTRAINT fk_comments_author
        FOREIGN KEY (author_id) REFERENCES helpdesk.users (id),
    content    TEXT      NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE helpdesk.ticket_histories
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT       NOT NULL,
    CONSTRAINT fk_ticket_histories_ticket
        FOREIGN KEY (ticket_id) REFERENCES helpdesk.tickets (id),
    actor_id   BIGINT       NOT NULL,
    CONSTRAINT fk_ticket_histories_actor
        FOREIGN KEY (actor_id) REFERENCES helpdesk.users (id),
    field_name VARCHAR(50)  NOT NULL,
    old_value  VARCHAR(255),
    new_value  VARCHAR(255) NOT NULL,
    created_at TIMESTAMP    NOT NULL
);